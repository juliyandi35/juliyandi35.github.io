// Refreshes public/pohon/data.js from the GitHub API before each build (CI rebuilds daily, see deploy-pages.yml).
// On any failure the committed snapshot is kept, so the build never breaks because of GitHub.
import { writeFile } from 'node:fs/promises'

const USER = 'juliyandi35'
const OUT = new URL('../public/pohon/data.js', import.meta.url)
const MAIN_TOOLS = new Set(['R', 'SPSS', 'Excel', 'Python', 'Stata', 'MATLAB', 'SmartPLS'])

async function fetchRepos() {
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': `${USER}-pohon` }
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  const repos = []
  for (let page = 1; ; page++) {
    const res = await fetch(`https://api.github.com/users/${USER}/repos?per_page=100&page=${page}`, { headers })
    if (!res.ok) throw new Error(`GitHub API ${res.status} ${res.statusText}`)
    const batch = await res.json()
    repos.push(...batch)
    if (batch.length < 100) return repos
  }
}

// Descriptions follow "Category | other category | Tool, tool". Repos without that shape are apps and misc.
function toRow(r) {
  const d = (r.description || '').trim()
  let cat = 'Aplikasi & lain-lain', tool = 'Lainnya', desc = d
  if (d.includes('|')) {
    const p = d.split('|').map((x) => x.trim())
    cat = p[0]
    tool = p.at(-1).split(/[,/]/)[0].trim()
    desc = p.slice(1).join(' | ')
  }
  if (!MAIN_TOOLS.has(tool)) tool = 'Lainnya'
  return [r.name, cat, tool, desc.slice(0, 160), r.stargazers_count, r.pushed_at.slice(0, 10), r.created_at.slice(0, 10), r.size]
}

try {
  const repos = await fetchRepos()
  if (!repos.length) throw new Error('no repositories returned')
  const rows = repos.sort((a, b) => b.pushed_at.localeCompare(a.pushed_at)).map(toRow)
  const today = new Date().toISOString().slice(0, 10)
  const js =
    `// [name, category, tool, desc, stars, pushed, created, sizeKB]: generated by scripts/pohon-data.mjs\n` +
    `const D_DATE = ${JSON.stringify(today)};\nconst D = ${JSON.stringify(rows)};\n`
  await writeFile(OUT, js)
  console.log(`pohon: ${rows.length} repositories written (${today})`)
} catch (err) {
  console.warn(`pohon: keeping the committed snapshot (${err.message})`)
}
